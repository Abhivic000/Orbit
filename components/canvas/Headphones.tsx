"use client";

import { useGLTF } from "@react-three/drei";
import { invalidate, useFrame, type ThreeElements } from "@react-three/fiber";
import { useEffect, useMemo, useRef, type ReactNode } from "react";
import type { BufferGeometry, Group, Material, Mesh, Object3D } from "three";
import type { GLTF } from "three/examples/jsm/loaders/GLTFLoader.js";
import { useConfig } from "@/lib/configState";
import { partOffset } from "@/lib/explode";
import {
  applyColourway,
  applyHeadband,
  getMaterials,
  setCushionSheen,
  type HaloMaterials,
} from "@/lib/materials";
import { EXPLODE_COUNT, explodeFor } from "@/lib/parts";
import { rig } from "@/lib/rig";
import { Internals } from "./Internals";
import { SHADOW_SKIP_LAYER } from "./layers";

export const MODEL_URL = { high: "/models/halo-one.glb", low: "/models/halo-one-mobile.glb" };
export const DRACO_PATH = "/draco/";

export { SHADOW_SKIP_LAYER };
const NO_SHADOW = new Set<string>([
  "ButtonPlus",
  "Buttons",
  "Port",
  "Hinge_L",
  "Hinge_R",
  "Grille_L",
  "Grille_R",
]);

type PartName =
  | "CupRim_L" | "CupRim_R" | "HeadbandShell" | "Yoke_L" | "Yoke_R" | "CupCap_L" | "CupCap_R"
  | "Housing_L" | "Housing_R" | "SliderBlock_L" | "SliderBlock_R" | "Slider_L" | "Slider_R"
  | "ButtonPlus" | "Buttons" | "Port" | "Cushion_L" | "Cushion_R" | "Hinge_L" | "Hinge_R"
  | "HeadbandPad" | "Grille_L" | "Grille_R"; // prettier-ignore

type GLTFResult = GLTF & {
  nodes: Record<PartName, Mesh>;
  materials: Record<
    "Shell" | "Trim" | "Metal" | "Cushion" | "Headband",
    Material & { normalMap: import("three").Texture | null }
  >;
};

/** Parts register here so one useFrame can move them all (no per-part hooks). */
export type PartRegistry = Map<string, { obj: Object3D; base: [number, number, number] }>;

export function useHaloMaterials(gltf: GLTFResult) {
  return useMemo(() => getMaterials(gltf.materials.Shell.normalMap), [gltf]);
}

type HeadphonesProps = ThreeElements["group"] & {
  url: string;
  /** Extra JSX attached to a named part (moves with it when exploded). */
  attach?: Partial<Record<string, ReactNode>>;
};

export function Headphones({ url, attach = {}, ...props }: HeadphonesProps) {
  const gltf = useGLTF(url, DRACO_PATH) as unknown as GLTFResult;
  const { nodes } = gltf;
  const m = useHaloMaterials(gltf);
  const parts = useRef<PartRegistry>(new Map());

  // Colourway + headband: mutate the shared materials (no React re-render of the mesh tree).
  useEffect(() => {
    const { colourway, material } = useConfig.getState();
    applyColourway(colourway, 0);
    applyHeadband(material);
    invalidate();
    return useConfig.subscribe((s, prev) => {
      if (s.colourway !== prev.colourway) applyColourway(s.colourway, 0.6, () => invalidate());
      if (s.material !== prev.material) {
        applyHeadband(s.material);
        invalidate();
      }
    });
  }, []);

  // Exploded view + cushion sheen: read the rig every frame, write to objects.
  const lastExplode = useRef(-1);
  useFrame(() => {
    setCushionSheen(rig.sheen);
    if (rig.explode === lastExplode.current) return;
    lastExplode.current = rig.explode;
    for (const [name, { obj, base }] of parts.current) {
      const e = explodeFor(name);
      if (!e) continue;
      const [dx, dy, dz] = partOffset(rig.explode, e.order, EXPLODE_COUNT, e.dir, e.distance);
      obj.position.set(base[0] + dx, base[1] + dy, base[2] + dz);
    }
  });

  const register = (name: string, base: [number, number, number]) => (obj: Object3D | null) => {
    if (obj) parts.current.set(name, { obj, base });
    else parts.current.delete(name);
  };

  const P = (name: PartName, material: Material, position: [number, number, number]) => (
    <mesh
      key={name}
      name={name}
      ref={register(name, position)}
      geometry={nodes[name].geometry as BufferGeometry}
      material={material}
      position={position}
      layers={NO_SHADOW.has(name) ? SHADOW_SKIP_LAYER : 0}
    >
      {attach[name]}
    </mesh>
  );

  return (
    <group {...props} dispose={null}>
      {P("CupRim_L", m.shell, [-0.378, -0.26, 0])}
      {P("CupRim_R", m.shell, [0.378, -0.26, 0])}
      {P("HeadbandShell", m.shell, [0, 0.231, 0])}
      {P("Yoke_L", m.shell, [-0.406, -0.086, 0])}
      {P("Yoke_R", m.shell, [0.406, -0.086, 0])}
      {P("CupCap_L", m.shell, [-0.427, -0.272, 0])}
      {P("CupCap_R", m.shell, [0.427, -0.272, 0])}
      {P("Housing_L", m.trim, [-0.319, -0.244, 0])}
      {P("Housing_R", m.trim, [0.319, -0.244, 0])}
      {P("SliderBlock_L", m.shell, [-0.408, 0.185, 0])}
      {P("SliderBlock_R", m.shell, [0.408, 0.185, 0])}
      {P("Slider_L", m.metal, [-0.395, 0.08, 0.004])}
      {P("Slider_R", m.metal, [0.395, 0.08, 0.004])}
      {P("ButtonPlus", m.trim, [0.339, -0.405, 0.142])}
      {P("Buttons", m.trim, [0.324, -0.453, 0.101])}
      {P("Port", m.trim, [-0.329, -0.439, 0.116])}
      {P("Cushion_L", m.accent, [-0.283, -0.237, 0])}
      {P("Cushion_R", m.accent, [0.283, -0.237, 0])}
      {P("Hinge_L", m.metal, [-0.465, 0.06, 0.001])}
      {P("Hinge_R", m.metal, [0.465, 0.06, 0.001])}
      {P("HeadbandPad", m.headband, [0, 0.227, 0])}
      {P("Grille_L", m.trim, [-0.289, -0.305, 0])}
      {P("Grille_R", m.trim, [0.289, -0.305, 0])}
      <Internals materials={m} register={register} attach={attach} />
    </group>
  );
}

